"""Derive a planning DAG from a captured canonical query; no network or state writes.

Default: generate DAG.md and graph.json. --check: compare without writing.
This validates dependency structure, not execution authorization or mathematics.
"""

from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/planning/tickets-2026-11-02.json"
IDENTIFIER = r"MATH-(?:[A-Z0-9]+-)+\d+"


def derive(data: dict) -> dict:
    if data["format"] != "mamut-math-planning/1" or data["coverage"]["query_has_more"]:
        raise ValueError("Unsupported or incomplete canonical query")
    rows = sorted(data["tickets"], key=lambda row: row["Orden"])
    by_id = {row["id"]: row for row in rows}
    if len(by_id) != len(rows) or len({row["Orden"] for row in rows}) != len(rows):
        raise ValueError("Duplicate ticket identity/order")
    hard, soft, external = set(), set(), []
    for row in rows:
        if re.match(IDENTIFIER, row["Ticket"])[0] != row["id"]:
            raise ValueError("Title/identity mismatch")
        if row["Estado"] not in {"Done", "Siguiente", "Planeado", "Blocked"}:
            raise ValueError("Unknown state")
        for clause in row["Dependencias"].split(";"):
            clause = clause.strip()
            if clause == "None":
                continue
            match = re.fullmatch(rf"(HARD|SOFT)\s+({IDENTIFIER})", clause)
            if not match:
                if clause.startswith("SOFT ") and "MATH-" not in clause:
                    external.append({"target": row["id"], "note": clause[5:]})
                    continue
                raise ValueError(f"Unparsed dependency: {row['id']} / {clause}")
            kind, prerequisite = match.groups()
            if prerequisite not in by_id:
                raise ValueError(f"Unknown dependency: {prerequisite}")
            (hard if kind == "HARD" else soft).add((prerequisite, row["id"]))
    prerequisites = {key: set() for key in by_id}
    for source, target in hard:
        prerequisites[target].add(source)
    pending, done, layers = set(by_id), set(), []
    while pending:
        layer = [row["id"] for row in rows
                 if row["id"] in pending and prerequisites[row["id"]] <= done]
        if not layer:
            raise ValueError("HARD cycle")
        layers.append(layer)
        done.update(layer)
        pending.difference_update(layer)
    nodes = []
    for row in rows:
        unmet = sorted(key for key in prerequisites[row["id"]]
                       if by_id[key]["Estado"] != "Done")
        nodes.append({**row, "unmet_hard": unmet,
                      "table_ready": row["Estado"] == "Siguiente" and not unmet})
    return {"source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
            "observed_at_utc": data["observed_at_utc"], "nodes": nodes,
            "hard": sorted(hard), "soft": sorted(soft), "external_soft": external,
            "topological_layers": layers,
            "states": dict(Counter(row["Estado"] for row in rows)),
            "table_ready": [node["id"] for node in nodes if node["table_ready"]],
            "planned_hard_ready": [node["id"] for node in nodes
                                   if node["Estado"] == "Planeado" and not node["unmet_hard"]]}


def markdown(graph: dict) -> str:
    nodes = graph["nodes"]
    mermaid_id = lambda value: value.replace("-", "_")
    lines = ["<!-- Generated by scripts/planning/build_dag.py; do not hand-edit. -->",
             "# DAG de ejecución · snapshot 2026-11-02", "",
             f"Fuente: [Notion](https://app.notion.com/p/f3f9f65000d64435a415324e64d4a32b). Consulta: {graph['observed_at_utc']}.",
             f"{len(nodes)} tickets; {len(graph['hard'])} HARD; {len(graph['soft'])} SOFT internas; {len(graph['external_soft'])} SOFT externas. HARD acíclico.",
             "", "Las flechas van del prerequisito al dependiente. SOFT no bloquea.",
             "Las capas son estructurales: no son ondas autorizadas ni una ruta crítica por duración.",
             "Estado, release, snapshot, conflictos y STOP del ticket siguen siendo gates independientes.",
             "", "Entrada por tabla: " + ", ".join(graph["table_ready"]) + ".",
             "Planeado con HARD satisfechas (NO iniciar): " + ", ".join(graph["planned_hard_ready"]) + ".",
             "E2E-001 conserva su STOP después de M2; preparar el DAG no autoriza C1/C2/C3.",
             "", "## Grafo completo", "", "```mermaid", "flowchart TD"]
    releases = list(dict.fromkeys(row["Release"] for row in nodes))
    for index, release in enumerate(releases):
        lines.append(f'subgraph G{index}["{release or "Seguimientos · sin release asignada"}"]')
        for row in nodes:
            if row["Release"] == release:
                lines.append(f'{mermaid_id(row["id"])}["{row["id"]} · {row["Estado"]}"]')
        lines.append("end")
    for source, target in graph["hard"]:
        lines.append(f"{mermaid_id(source)} --> {mermaid_id(target)}")
    for source, target in graph["soft"]:
        lines.append(f"{mermaid_id(source)} -. SOFT .-> {mermaid_id(target)}")
    lines += ["```", "", "## Capas topológicas completas", "",
              "Incluyen Done y Planeado, sin simular cierres ni cambiar releases.", "",
              "| Capa | Tickets |", "| --- | --- |"]
    for index, layer in enumerate(graph["topological_layers"]):
        lines.append(f"| {index} | {', '.join(layer)} |")
    lines += ["", "## Gates por ticket", "",
              "Entrada=TABLA significa Siguiente y HARD Done; aún exige preflight, snapshot y autorización vigente.",
              "", "| Ticket | Estado | Release | HARD pendientes | Entrada |",
              "| --- | --- | --- | --- | --- |"]
    for row in nodes:
        lines.append(f"| [{row['id']}]({row['url']}) | {row['Estado']} | {row['Release'] or 'Sin asignar'} | {', '.join(row['unmet_hard']) or 'Ninguna'} | {'TABLA' if row['table_ready'] else 'Cerrado' if row['Estado'] == 'Done' else 'NO'} |")
    lines += ["", "## SOFT externas", ""]
    for edge in graph["external_soft"]:
        lines.append(f"- {edge['target']}: {edge['note']}.")
    lines += ["", "## Reproducir", "", "```powershell",
              "python scripts/planning/build_dag.py --check", "```", "",
              "Regenerar sin --check sólo después de capturar y revisar las propiedades canónicas.",
              "El script no consulta Notion ni actualiza estados; no es un sincronizador ni un snapshot de ejecución.", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    graph = derive(json.loads(SOURCE.read_text(encoding="utf-8")))
    outputs = {ROOT / "docs/planning/DAG.md": markdown(graph),
               ROOT / "docs/planning/graph.json": json.dumps(graph, ensure_ascii=False, indent=2) + "\n"}
    for path, content in outputs.items():
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"STALE: {path}")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    print(json.dumps({"status": "VERIFIED", "tickets": len(graph["nodes"]),
                      "hard": len(graph["hard"]), "soft": len(graph["soft"]),
                      "states": graph["states"], "table_ready": graph["table_ready"],
                      "planned_hard_ready": graph["planned_hard_ready"]}))


if __name__ == "__main__":
    main()
